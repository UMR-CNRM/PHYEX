#!/usr/bin/env python3
"""
Transformation of a PHYEX source file by pyfortool, executed at build time
(see the top-level CMakeLists.txt, PHYEX_TRANSFORMATION option):
    phyex_transform.py --transformation <name> [--pyfortool <exe>] <input> <output>

The new source code is generated by pyfortool with arguments depending on the
transformation, complemented by '--optsByEnv PYFT_OPTS' if the PYFT_OPTS
environment variable is not empty. It is written in a temporary file which is
renamed into <output> when the transformation succeeds.

The list of available transformations is printed with --list.
"""

import argparse
import os
import subprocess
import sys

# Transformation name -> pyfortool arguments
TRANSFORMATIONS = {
    'IAL': ['--wrapH', '--removeACC', '--shugradTransfo', '--mnhExpand', '--splitLongLines'],
    # IAL without the transformation of shuman/gradient functions into subroutine calls
    'IAL_NOSHUGRAD': ['--wrapH', '--removeACC', '--mnhExpand', '--splitLongLines'],
    # IAL without the expansion of the mnh_expand directives (code kept in array syntax)
    'IAL_NOEXPAND': ['--wrapH', '--removeACC', '--shugradTransfo', '--splitLongLines'],
}

# Name of the environment variable containing additional pyfortool arguments
OPTS_ENV = 'PYFT_OPTS'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--list', action='store_true',
                        help='Print the available transformations (;-separated) and exit')
    parser.add_argument('--transformation', choices=list(TRANSFORMATIONS),
                        help='Transformation to apply')
    parser.add_argument('--pyfortool', default='pyfortool', help='pyfortool executable')
    parser.add_argument('--unset-pythonpath', action='store_true',
                        help='Unset PYTHONPATH when running pyfortool')
    parser.add_argument('input', nargs='?', help='Original source file')
    parser.add_argument('output', nargs='?', help='Transformed source file')
    args = parser.parse_args()

    if args.list:
        print(';'.join(TRANSFORMATIONS))
        return 0
    if args.transformation is None or args.input is None or args.output is None:
        parser.error('--transformation, input and output are needed')

    outdir = os.path.dirname(os.path.abspath(args.output))
    os.makedirs(outdir, exist_ok=True)
    stem, ext = os.path.splitext(os.path.basename(args.output))
    tmp = os.path.join(outdir, f'{stem}.pyft_tmp{ext}')
    if os.path.exists(tmp):
        os.remove(tmp)

    cmd = [args.pyfortool] + TRANSFORMATIONS[args.transformation]
    if os.environ.get(OPTS_ENV, ''):
        cmd += ['--optsByEnv', OPTS_ENV]
    cmd += [args.input, tmp]
    env = None
    if args.unset_pythonpath:
        env = dict(os.environ)
        env.pop('PYTHONPATH', None)
    try:
        status = subprocess.run(cmd, env=env, check=False).returncode
    except OSError as err:
        print(f'phyex_transform: unable to execute {cmd[0]}: {err}', file=sys.stderr)
        status = 1
    if status != 0 or not os.path.exists(tmp):
        print(f'phyex_transform: transformation {args.transformation} of {args.input} failed: ' +
              ' '.join(cmd), file=sys.stderr)
        if os.path.exists(tmp):
            os.remove(tmp)
        return status or 1

    os.replace(tmp, args.output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
